#!/usr/bin/env python3
"""Build guide.js from guide.html. guide.html is the source of truth: edit it, run this, commit, push."""
import json, re, pathlib
here = pathlib.Path(__file__).parent
src = (here / "guide.html").read_text(encoding="utf-8")
scripts = re.findall(r"<script>(.*?)</script>", src, re.S)
markup = re.sub(r"<script>.*?</script>", "", src, flags=re.S).strip()
js = ("/* LOBSTERIA eating guide. Generated by build.py from guide.html. Do not edit. */\n"
      "(function(){var s=document.currentScript,r=document.getElementById('lbg-root'),"
      "t=document.createElement('template');t.innerHTML=" + json.dumps(markup) + ";"
      "if(r){r.appendChild(t.content);}else{s.parentNode.insertBefore(t.content,s);}})();\n"
      + "\n".join(scripts))
(here / "guide.js").write_text(js, encoding="utf-8")
print("guide.js", len(js), "bytes")
